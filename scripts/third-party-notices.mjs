import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));

// Use the production source maps so notices cover bundled code, not build-only dependencies.
export async function generateThirdPartyNotices() {
  const packages = new Map();
  for (const bundle of ['extension.cjs', 'webview.js', 'webview.css']) {
    const mapPath = path.join(root, 'dist', `${bundle}.map`);
    const map = JSON.parse(await readFile(mapPath, 'utf8'));
    for (const source of map.sources) {
      if (!source.split('/').includes('node_modules')) continue;
      let directory = path.dirname(
        path.resolve(path.dirname(mapPath), map.sourceRoot ?? '', source),
      );
      let found = false;
      while (directory.split(path.sep).includes('node_modules')) {
        let manifest;
        try {
          manifest = JSON.parse(await readFile(path.join(directory, 'package.json'), 'utf8'));
        } catch (error) {
          if (error.code !== 'ENOENT') throw error;
          directory = path.dirname(directory);
          continue;
        }
        if (!manifest.name || !manifest.version || typeof manifest.license !== 'string') {
          throw new Error(`Missing package or license metadata: ${directory}`);
        }
        packages.set(`${manifest.name}@${manifest.version}`, { directory, manifest });
        found = true;
        break;
      }
      if (!found) throw new Error(`No dependency manifest found for ${source}`);
    }
  }

  const sections = [];
  for (const [name, { directory, manifest }] of [...packages].sort(([a], [b]) =>
    a.localeCompare(b),
  )) {
    const files = (await readdir(directory, { withFileTypes: true }))
      .filter((file) => file.isFile() && /^(licen[cs]e|notice|copying)(\.|$)/i.test(file.name))
      .map((file) => file.name)
      .sort();
    if (!files.some((file) => /^(licen[cs]e|copying)(\.|$)/i.test(file))) {
      throw new Error(`No license text found for ${name}`);
    }
    const texts = await Promise.all(
      files.map(async (file) => {
        const content = await readFile(path.join(directory, file), 'utf8');
        return `${file}\n\n${content.trimEnd()}`;
      }),
    );
    sections.push(
      `${'='.repeat(72)}\n${name}\nLicense: ${manifest.license}\n\n${texts.join('\n\n')}`,
    );
  }
  if (!sections.length) throw new Error('No bundled dependencies found; run pnpm build first.');
  const header = `Canvas Studio — Third-party notices

The following software is included in the production extension bundles.
Each component remains subject to its own license reproduced below.
Build tools and type definitions are not included in these bundles.

Generated by scripts/third-party-notices.mjs from production bundle source maps.
Run pnpm build && pnpm licenses:generate after dependency changes.
`;
  await writeFile(
    path.join(root, 'THIRD_PARTY_NOTICES.txt'),
    `${header}\n${sections.join('\n\n')}\n`,
  );
  console.log(`Updated third-party notices for ${packages.size} bundled packages.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await generateThirdPartyNotices();
}
